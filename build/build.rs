/// build.rs - 嵌入应用清单（manifest）和应用图标到 Windows 可执行文件
///
/// 这确保 Windows 识别 Per-Monitor DPI V2 感知声明，
/// 防止在跨显示器（不同 DPI）移动窗口时做 bitmap-stretch 导致模糊。
///
/// 同时将 `logo.ico` 作为资源 ID=1 的 ICON 资源嵌入到 .exe 中，
/// 供运行时系统托盘、右键菜单和窗口标题栏使用。
fn main() {
    #[cfg(target_os = "windows")]
    {
        embed_manifest();
    }
}

#[cfg(target_os = "windows")]
fn embed_manifest() {
    use std::env;
    use std::fs;
    use std::path::{Path, PathBuf};

    let out_dir = env::var("OUT_DIR").unwrap();
    let manifest_dir = env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| env::current_dir().unwrap_or_default());
    let manifest_path = "build/app.manifest";

    // --- 解析 logo.ico 路径 ---
    // 优先使用 CARGO_MANIFEST_DIR（即 Cargo.toml 所在目录）拼接绝对路径，
    // 这比依赖 cwd（cargo 约定为包根）更稳健，能防止某些构建环境下路径解析失败。
    let logo_path = manifest_dir.join("logo.ico");
    let logo_exists = logo_path.exists();
    if !logo_exists {
        // 兜底：尝试相对路径（兼容旧行为）
        let fallback = Path::new("logo.ico");
        if fallback.exists() {
            eprintln!(
                "cargo:warning=logo.ico 通过相对路径找到（CARGO_MANIFEST_DIR={} 未包含该文件）",
                manifest_dir.display()
            );
        }
    }

    let has_icon = logo_exists || Path::new("logo.ico").exists();

    if !Path::new(manifest_path).exists() {
        eprintln!("cargo:warning=build/app.manifest not found, skipping embed");
        return;
    }

    // --- 生成 .rc 文件（引用 manifest + 可选应用图标）---
    let rc_content = if has_icon {
        // 使用绝对路径并转换为正斜杠（windres 不支持扩展长度路径，且会将反斜杠解释为转义字符）
        let manifest_abs = Path::new(manifest_path)
            .canonicalize()
            .unwrap_or_else(|_| Path::new(manifest_path).to_path_buf());
        let icon_abs = if logo_exists {
            logo_path
                .canonicalize()
                .unwrap_or_else(|_| logo_path.clone())
        } else {
            Path::new("logo.ico")
                .canonicalize()
                .unwrap_or_else(|_| Path::new("logo.ico").to_path_buf())
        };
        let manifest_str = manifest_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        let icon_str = icon_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        println!("cargo:warning=嵌入应用图标: {}", icon_str);
        format!(
            r#"// Auto-generated by build.rs - embed application manifest and icon
1 24 "{}"
1 ICON "{}"
"#,
            manifest_str, icon_str
        )
    } else {
        eprintln!("cargo:warning=logo.ico not found at {} or project root, skipping icon embed. 请将 logo.ico 放置到项目根目录。", logo_path.display());
        let manifest_abs = Path::new(manifest_path)
            .canonicalize()
            .unwrap_or_else(|_| Path::new(manifest_path).to_path_buf());
        let manifest_str = manifest_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        format!(
            r#"// Auto-generated by build.rs - embed application manifest
1 24 "{}"
"#,
            manifest_str
        )
    };
    let rc_path = Path::new(&out_dir).join("app.rc");
    fs::write(&rc_path, &rc_content).expect("Failed to write .rc file");

    // --- 方案 A: 尝试 windres (MinGW) - 输出 COFF .o 文件 ---
    let obj_path = Path::new(&out_dir).join("app_manifest.o");
    let windres_status = std::process::Command::new("windres")
        .arg(&rc_path)
        .arg("-o")
        .arg(&obj_path)
        .output();

    match &windres_status {
        Ok(output) if output.status.success() => {
            println!("cargo:rustc-link-arg={}", obj_path.display());
            emit_rerun_triggers();
            println!(
                "cargo:warning=windres 编译 .rc 成功: {}",
                obj_path.display()
            );
            return;
        }
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            eprintln!(
                "cargo:warning=windres 编译 .rc 失败 (exit={}): {}",
                output.status,
                stderr.trim()
            );
        }
        Err(e) => {
            eprintln!(
                "cargo:warning=windres 不可用: {}（请安装 MinGW-w64 或确保 windres 在 PATH 中）",
                e
            );
        }
    }

    // --- 方案 B: 尝试 rc.exe + cvtres.exe (MSVC toolchain) ---
    let res_path = Path::new(&out_dir).join("app.res");
    let rc_status = std::process::Command::new("rc.exe")
        .arg("/fo")
        .arg(&res_path)
        .arg(&rc_path)
        .output();

    match &rc_status {
        Ok(output) if output.status.success() => {
            // cvtres 将 .res 转换为链接器可用的 .obj
            let obj_path_msvc = Path::new(&out_dir).join("app_manifest.obj");
            let cvtres_output = std::process::Command::new("cvtres.exe")
                .arg("/machine:x64")
                .arg("/out")
                .arg(&obj_path_msvc)
                .arg(&res_path)
                .output();

            match &cvtres_output {
                Ok(out) if out.status.success() => {
                    println!("cargo:rustc-link-arg={}", obj_path_msvc.display());
                    emit_rerun_triggers();
                    println!(
                        "cargo:warning=rc.exe + cvtres.exe 编译 .rc 成功: {}",
                        obj_path_msvc.display()
                    );
                    return;
                }
                Ok(out) => {
                    let stderr = String::from_utf8_lossy(&out.stderr);
                    eprintln!(
                        "cargo:warning=cvtres.exe 失败 (exit={}): {}",
                        out.status,
                        stderr.trim()
                    );
                }
                Err(e) => {
                    eprintln!("cargo:warning=cvtres.exe 不可用: {}", e);
                }
            }
        }
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            eprintln!(
                "cargo:warning=rc.exe 编译 .rc 失败 (exit={}): {}",
                output.status,
                stderr.trim()
            );
        }
        Err(e) => {
            eprintln!("cargo:warning=rc.exe 不可用: {}（请安装 Visual Studio Build Tools 或 Windows SDK）", e);
        }
    }

    // --- 方案 C: 尝试直接链接 .res（部分链接器支持）---
    if res_path.exists() {
        println!("cargo:rustc-link-arg={}", res_path.display());
        emit_rerun_triggers();
        println!("cargo:warning=回退：直接链接 .res 文件（rc.exe 成功但 cvtres 不可用）");
        return;
    }

    // --- 全部失败 ---
    emit_rerun_triggers();
    let icon_msg = if has_icon { "和图标" } else { "" };
    eprintln!("cargo:warning=═══════════════════════════════════════════════════");
    eprintln!(
        "cargo:warning=无法嵌入 manifest{}：windres 和 rc.exe 均不可用！",
        icon_msg
    );
    eprintln!("cargo:warning=这意味着编译出的 .exe 将没有应用图标和 DPI 声明。");
    eprintln!("cargo:warning=");
    eprintln!("cargo:warning=解决方法（任选其一）：");
    eprintln!("cargo:warning=  1. 安装 MinGW-w64（提供 windres）");
    eprintln!("cargo:warning=  2. 安装 Visual Studio Build Tools 或 Windows SDK（提供 rc.exe）");
    eprintln!("cargo:warning=═══════════════════════════════════════════════════");
    // 图标嵌入是发行版的必要条件，必须 panic 中断编译
    panic!(
        "资源编译工具不可用：windres 和 rc.exe 均未找到。\n\
         请安装 MinGW-w64 或 Visual Studio Build Tools / Windows SDK，\n\
         然后重新执行 cargo build。"
    );
}

fn emit_rerun_triggers() {
    println!("cargo:rerun-if-changed=build/app.manifest");
    println!("cargo:rerun-if-changed=build/build.rs");
    println!("cargo:rerun-if-changed=logo.ico");
}
