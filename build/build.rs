//! build.rs - 将应用清单嵌入 Windows 可执行文件，并集成 Tauri 2.0 构建流程。
//!
//! 确保 Windows 识别 Per-Monitor DPI V2 感知，
//! 防止窗口跨不同 DPI 显示器移动时被 bitmap-stretch。
//!
//! 应用图标统一由 tauri-build 嵌入（`WindowsAttributes::window_icon_path`，
//! RT_GROUP_ICON ID=32512）。本文件不再另行嵌入 ICON 资源：
//! 同一个 .ico 被两处嵌入时，各自拆出的 RT_ICON 子图像 ID 都从 1 开始，
//! MSVC 链接器 cvtres 会报 CVT1100 duplicate resource（GNU ld 容忍重复，
//! 因此之前一直未暴露）。运行时图标加载有 ID=1 -> ID=32512
//! 的回退链，见 src/platform/windows/app_icon.rs。
//!
//! 清单编译使用 embed-resource crate（与 tauri-build 相同的资源编译器发现机制）：
//! - MSVC 目标：PATH 中的 rc.exe / Windows SDK 注册表（KitsRoot10 等）/ vswhom 探测
//! - GNU 目标：PATH 中的 windres（含交叉前缀与 llvm-windres）
//!
//! 保证在 rc.exe / windres 不在 PATH 的机器上（如仅安装 VS Build Tools 的电脑）
//! 也能成功嵌入清单。

fn main() {
    // Tauri 2.0 构建集成（仅在 tauri-ui feature 启用时）
    #[cfg(feature = "tauri-ui")]
    {
        // 使用 logo.ico 作为 Tauri 窗口图标（嵌入资源 ID 32512），
        // 并关闭 tauri 默认 manifest，避免与本项目 manifest 重复嵌入 RT_MANIFEST。
        let attrs = tauri_build::Attributes::new().windows_attributes(
            tauri_build::WindowsAttributes::new_without_app_manifest().window_icon_path("logo.ico"),
        );
        if let Err(error) = tauri_build::try_build(attrs) {
            panic!("tauri_build 构建失败: {error:#}");
        }
    }

    #[cfg(target_os = "windows")]
    {
        embed_manifest();
    }
}

/// 将路径转换为 .rc 文件可用的正斜杠字符串（去除 UNC 前缀）。
fn rc_path_str(path: &std::path::Path) -> String {
    path.to_string_lossy()
        .replace("\\\\?\\", "")
        .replace('\\', "/")
}

#[cfg(target_os = "windows")]
fn embed_manifest() {
    use std::env;
    use std::fs;
    use std::path::Path;

    let out_dir = env::var("OUT_DIR").unwrap();
    let manifest_path = Path::new("build/app.manifest");

    if !manifest_path.exists() {
        eprintln!("cargo:warning=build/app.manifest not found, skipping embed");
        return;
    }

    let manifest_abs = manifest_path
        .canonicalize()
        .unwrap_or_else(|_| manifest_path.to_path_buf());
    let manifest_str = rc_path_str(&manifest_abs);

    // .rc 只含 manifest。图标由 tauri-build 统一嵌入（ID=32512），
    // 避免两处嵌入同一 .ico 导致 MSVC cvtres 报重复资源。
    let rc_content = format!(
        "// Auto-generated by build.rs - embed application manifest\n1 24 \"{manifest_str}\"\n"
    );
    let rc_path = Path::new(&out_dir).join("app.rc");
    fs::write(&rc_path, &rc_content).expect("Failed to write .rc file");

    println!("cargo:rerun-if-changed=build/app.manifest");
    println!("cargo:rerun-if-changed=build/build.rs");

    // --- 使用 embed-resource 编译并链接资源（与 tauri-build 相同的发现机制）---
    match embed_resource::compile(&rc_path, embed_resource::NONE).manifest_optional() {
        Ok(()) => {
            println!(
                "cargo:warning=embed-resource compiled manifest successfully: {}",
                rc_path.display()
            );
        }
        Err(result) => {
            eprintln!("cargo:warning=Cannot embed manifest via embed-resource: {result:?}");
            eprintln!(
                "cargo:warning=The .exe will have no DPI manifest. \
                 Install Windows SDK (rc.exe) or MinGW-w64 (windres), then rebuild."
            );

            // 仅在非 tauri-ui 模式中断构建（Tauri 有自己的资源处理）
            #[cfg(not(feature = "tauri-ui"))]
            {
                panic!(
                    "Resource compiler unavailable: neither windres nor rc.exe found.\n\
                     Install MinGW-w64 or Visual Studio Build Tools / Windows SDK, then rebuild."
                );
            }
        }
    }
}
