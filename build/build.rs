/// build.rs - Embed application manifest and icon into Windows executable,
/// plus Tauri 2.0 build integration.
///
/// Ensures Windows recognizes Per-Monitor DPI V2 awareness,
/// preventing bitmap-stretch when moving windows across monitors with different DPI.
///
/// Also embeds `logo.ico` as resource ID=1 ICON for system tray and window title bars.

fn main() {
    // Tauri 2.0 build integration (only when tauri-ui feature is enabled)
    #[cfg(feature = "tauri-ui")]
    {
        tauri_build::build();
    }

    #[cfg(target_os = "windows")]
    {
        embed_manifest();
    }
}

#[cfg(target_os = "windows")]
fn embed_manifest() {
    use std::env;
    use std::fs;
    use std::path::{Path, PathBuf};

    let out_dir = env::var("OUT_DIR").unwrap();
    let manifest_dir = env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| env::current_dir().unwrap_or_default());
    let manifest_path = "build/app.manifest";

    // --- Resolve logo.ico path ---
    let logo_path = manifest_dir.join("logo.ico");
    let logo_exists = logo_path.exists();
    if !logo_exists {
        let fallback = Path::new("logo.ico");
        if fallback.exists() {
            eprintln!(
                "cargo:warning=logo.ico found via relative path (CARGO_MANIFEST_DIR={} does not contain it)",
                manifest_dir.display()
            );
        }
    }

    let has_icon = logo_exists || Path::new("logo.ico").exists();

    if !Path::new(manifest_path).exists() {
        eprintln!("cargo:warning=build/app.manifest not found, skipping embed");
        return;
    }

    // --- Generate .rc file (references manifest + optional icon) ---
    let rc_content = if has_icon {
        let manifest_abs = Path::new(manifest_path)
            .canonicalize()
            .unwrap_or_else(|_| Path::new(manifest_path).to_path_buf());
        let icon_abs = if logo_exists {
            logo_path
                .canonicalize()
                .unwrap_or_else(|_| logo_path.clone())
        } else {
            Path::new("logo.ico")
                .canonicalize()
                .unwrap_or_else(|_| Path::new("logo.ico").to_path_buf())
        };
        let manifest_str = manifest_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        let icon_str = icon_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        println!("cargo:warning=Embedding app icon: {}", icon_str);
        format!(
            r#"// Auto-generated by build.rs - embed application manifest and icon
1 24 "{}"
1 ICON "{}"
"#,
            manifest_str, icon_str
        )
    } else {
        eprintln!(
            "cargo:warning=logo.ico not found at {} or project root, skipping icon embed.",
            logo_path.display()
        );
        let manifest_abs = Path::new(manifest_path)
            .canonicalize()
            .unwrap_or_else(|_| Path::new(manifest_path).to_path_buf());
        let manifest_str = manifest_abs
            .to_string_lossy()
            .replace("\\\\?\\", "")
            .replace("\\", "/");
        format!(
            r#"// Auto-generated by build.rs - embed application manifest
1 24 "{}"
"#,
            manifest_str
        )
    };
    let rc_path = Path::new(&out_dir).join("app.rc");
    fs::write(&rc_path, &rc_content).expect("Failed to write .rc file");

    // --- Method A: Try windres (MinGW) ---
    let obj_path = Path::new(&out_dir).join("app_manifest.o");
    let windres_status = std::process::Command::new("windres")
        .arg(&rc_path)
        .arg("-o")
        .arg(&obj_path)
        .output();

    match &windres_status {
        Ok(output) if output.status.success() => {
            println!("cargo:rustc-link-arg={}", obj_path.display());
            emit_rerun_triggers();
            println!(
                "cargo:warning=windres compiled .rc successfully: {}",
                obj_path.display()
            );
            return;
        }
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            eprintln!(
                "cargo:warning=windres failed (exit={}): {}",
                output.status,
                stderr.trim()
            );
        }
        Err(e) => {
            eprintln!("cargo:warning=windres not available: {}", e);
        }
    }

    // --- Method B: Try rc.exe + cvtres.exe (MSVC toolchain) ---
    let res_path = Path::new(&out_dir).join("app.res");
    let rc_status = std::process::Command::new("rc.exe")
        .arg("/fo")
        .arg(&res_path)
        .arg(&rc_path)
        .output();

    match &rc_status {
        Ok(output) if output.status.success() => {
            let obj_path_msvc = Path::new(&out_dir).join("app_manifest.obj");
            let cvtres_output = std::process::Command::new("cvtres.exe")
                .arg("/machine:x64")
                .arg("/out")
                .arg(&obj_path_msvc)
                .arg(&res_path)
                .output();

            match &cvtres_output {
                Ok(out) if out.status.success() => {
                    println!("cargo:rustc-link-arg={}", obj_path_msvc.display());
                    emit_rerun_triggers();
                    println!(
                        "cargo:warning=rc.exe + cvtres.exe compiled .rc successfully: {}",
                        obj_path_msvc.display()
                    );
                    return;
                }
                Ok(out) => {
                    let stderr = String::from_utf8_lossy(&out.stderr);
                    eprintln!(
                        "cargo:warning=cvtres.exe failed (exit={}): {}",
                        out.status,
                        stderr.trim()
                    );
                }
                Err(e) => {
                    eprintln!("cargo:warning=cvtres.exe not available: {}", e);
                }
            }
        }
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            eprintln!(
                "cargo:warning=rc.exe failed (exit={}): {}",
                output.status,
                stderr.trim()
            );
        }
        Err(e) => {
            eprintln!("cargo:warning=rc.exe not available: {}", e);
        }
    }

    // --- Method C: Try direct .res linking ---
    if res_path.exists() {
        println!("cargo:rustc-link-arg={}", res_path.display());
        emit_rerun_triggers();
        println!("cargo:warning=Fallback: linking .res directly (rc.exe succeeded but cvtres unavailable)");
        return;
    }

    // --- All methods failed ---
    emit_rerun_triggers();
    let icon_msg = if has_icon { " and icon" } else { "" };
    eprintln!(
        "cargo:warning=Cannot embed manifest{}: neither windres nor rc.exe available!",
        icon_msg
    );
    eprintln!("cargo:warning=The .exe will have no app icon and DPI declaration.");

    // Only panic if not in tauri-ui mode (Tauri has its own resource handling)
    #[cfg(not(feature = "tauri-ui"))]
    {
        panic!(
            "Resource compiler unavailable: windres and rc.exe not found.\n\
             Install MinGW-w64 or Visual Studio Build Tools / Windows SDK, then rebuild."
        );
    }
}

fn emit_rerun_triggers() {
    println!("cargo:rerun-if-changed=build/app.manifest");
    println!("cargo:rerun-if-changed=build/build.rs");
    println!("cargo:rerun-if-changed=logo.ico");
}
